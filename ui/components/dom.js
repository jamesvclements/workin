export function icon(name) {
  const wrapper = document.createElement("span");
  wrapper.className = "ui-icon";
  wrapper.setAttribute("aria-hidden", "true");
  wrapper.innerHTML = iconAssets[name] || "";
  if (name === "slack") {
    const original = wrapper.querySelector("path");
    const segments = original.getAttribute("d").match(/M[^M]+/g);
    original.remove();
    const colors = ["#e01e5a", "#36c5f0", "#2eb67d", "#ecb22e"];
    segments.forEach((segment, index) => {
      const path = document.createElementNS(
        "http://www.w3.org/2000/svg",
        "path",
      );
      path.setAttribute("d", segment);
      path.style.fill = colors[Math.floor(index / 2)];
      wrapper.querySelector("svg").appendChild(path);
    });
  }
  return wrapper;
}

export function element(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

export function safeUrl(value) {
  try {
    if (typeof value !== "string" || !value.trim()) return null;
    const url = new URL(value, document.baseURI);
    return ["https:", "http:"].includes(url.protocol) ? url.href : null;
  } catch {
    return null;
  }
}

export function sourceLink(label, value) {
  const link = element("a", "", label);
  const url = safeUrl(value);
  if (url) {
    link.href = url;
    link.target = "_blank";
    link.rel = "noopener noreferrer";
  }
  return link;
}

export function appendBody(parent, source, emojiImages = {}) {
  const body = element("div", "source-body");
  const parts = source.parts || [{ text: source.text || "" }];
  for (const part of parts) {
    if (part.style === "codeblock") {
      const block = element("pre");
      block.appendChild(element("code", "", part.text));
      body.appendChild(block);
      continue;
    }
    const node = part.url
      ? sourceLink(part.text, part.url)
      : element(
          part.style === "code"
            ? "code"
            : part.style === "bold"
              ? "strong"
              : part.style === "italic"
                ? "em"
                : "span",
          "",
          part.text,
        );
    if (part.image && safeUrl(part.image)) {
      const emoji = element("img", "inline-emoji");
      emoji.src =
        safeUrl(emojiImages?.[part.text?.replace(/^:|:$/g, "")]) ||
        safeUrl(part.image);
      emoji.alt = part.text;
      body.appendChild(emoji);
    } else {
      if (source.type === "slack" && part.style !== "code") {
        node.textContent = "";
        let cursor = 0;
        for (const match of part.text.matchAll(/:([a-zA-Z0-9_+-]+):/g)) {
          node.appendChild(
            document.createTextNode(part.text.slice(cursor, match.index)),
          );
          const image = safeUrl(emojiImages?.[match[1]]);
          if (image) {
            const emoji = element("img", "inline-emoji");
            emoji.alt = match[0];
            emoji.title = match[0];
            emoji.addEventListener(
              "error",
              () => emoji.replaceWith(document.createTextNode(match[0])),
              { once: true },
            );
            emoji.src = image;
            node.appendChild(emoji);
          } else node.appendChild(document.createTextNode(match[0]));
          cursor = match.index + match[0].length;
        }
        node.appendChild(document.createTextNode(part.text.slice(cursor)));
      }
      body.appendChild(node);
    }
  }
  if (source.type === "slack") {
    const lines = [document.createDocumentFragment()];
    function split(node, ancestors = []) {
      if (node.nodeType === Node.TEXT_NODE) {
        node.textContent.split("\n").forEach((text, index) => {
          if (index) lines.push(document.createDocumentFragment());
          let content = document.createTextNode(text);
          for (let depth = ancestors.length - 1; depth >= 0; depth--) {
            const wrapper = ancestors[depth].cloneNode(false);
            wrapper.appendChild(content);
            content = wrapper;
          }
          lines.at(-1).appendChild(content);
        });
      } else if (node.matches("pre, img"))
        lines.at(-1).appendChild(node.cloneNode(true));
      else
        for (const child of node.childNodes) split(child, [...ancestors, node]);
    }
    for (const child of body.childNodes) split(child);
    body.replaceChildren();
    body.style.whiteSpace = "normal";
    let list = null;
    let paragraph = null;
    for (const line of lines) {
      const text = line.textContent;
      if (!text.trim() && !line.querySelector("img, pre")) {
        paragraph = null;
        list = null;
        continue;
      }
      const marker = text.match(/^\s*(?:>\s*)?(\d+\.|[a-z]\.|[•-])\s+/);
      if (marker) {
        const kind = /^[•-]/.test(marker[1]) ? "ul" : "ol";
        const alpha = /^[a-z]/.test(marker[1]);
        if (
          !list ||
          list.tagName.toLowerCase() !== kind ||
          list.type !== (alpha ? "a" : "")
        ) {
          list = element(kind);
          if (alpha) list.type = "a";
          else if (kind === "ol") list.start = parseInt(marker[1], 10);
          body.appendChild(list);
        }
        const walker = document.createTreeWalker(line, NodeFilter.SHOW_TEXT);
        let remaining = marker[0].length;
        while (remaining && walker.nextNode()) {
          const node = walker.currentNode;
          const removed = Math.min(remaining, node.textContent.length);
          node.textContent = node.textContent.slice(removed);
          remaining -= removed;
        }
        const item = element("li");
        item.appendChild(line);
        list.appendChild(item);
        paragraph = null;
      } else {
        list = null;
        if (!paragraph) {
          paragraph = element("p");
          body.appendChild(paragraph);
        } else paragraph.appendChild(element("br"));
        paragraph.appendChild(line);
      }
    }
  }
  parent.appendChild(body);
}
